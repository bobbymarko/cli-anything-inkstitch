# Fabric presets for satin columns: stitch spacing, pull compensation, and the underlay ladder by
# column width (the usual digitizing ladder, as ES's automatic underlay: a centre walk under thin
# columns, an edge walk (contour) above that, edge walk plus zigzag on wide ones). "standard" is the
# ladder text-to-satin has always used (the engine's default spacing). Stable woven fabric (twill,
# canvas) needs less underlay and pull compensation than fleece or knit, which stretch and sink.
#
# Short stitches (short_inset, short_dist_mm; reader lib/elements/satin_column.py _get_offset_px): where
# a rail's consecutive stitch ends land closer than short_dist_mm (the inside of a tight turn), every
# other one stops short by short_inset of the column's width ("30 50": 30 %, then 50 % for the next
# in a run), so thread doesn't pile up there. short_dist_mm must stay below the rail's normal spacing
# (about the satin spacing): above it every stitch is shortened and the whole column thins. None keeps
# the engine's default (15 %, 0.25 mm).
FABRICS = {
    #            spacing  pull  centre walk below  zigzag from (mm)
    "standard": dict(spacing_mm=None, pull_comp_mm=0.2, center_below_mm=1.5, zigzag_from_mm=4.0,
                     short_inset=None, short_dist_mm=None),
    "twill":    dict(spacing_mm=0.4, pull_comp_mm=0.2, center_below_mm=2.0, zigzag_from_mm=5.0,
                     short_inset="30 50", short_dist_mm=0.25),
    "knit":     dict(spacing_mm=0.4, pull_comp_mm=0.3, center_below_mm=1.5, zigzag_from_mm=4.0,
                     short_inset="30 50", short_dist_mm=0.25),
    "fleece":   dict(spacing_mm=0.38, pull_comp_mm=0.3, center_below_mm=1.5, zigzag_from_mm=3.0,
                     short_inset="30 50", short_dist_mm=0.25),
}


def _schema_known(schema, stitch_type: str, params: dict, skipped: set) -> dict:
    """A preset's params less any the loaded schema doesn't know (an older engine, or the built-in
    bootstrap schema when the engine source hasn't been mined): one unknown name would make the
    whole element's params fail, and it would sew as a plain stroke. Skipped names are collected
    in `skipped` for the report. Explicit overrides aren't filtered: an unknown one should fail."""
    known = set(((schema.get("stitch_types") or {}).get(stitch_type) or {}).get("params") or {})
    if not known:
        return params
    out = {}
    for k, v in params.items():
        if k in known:
            out[k] = v
        else:
            skipped.add(k)
    return out


def shape_band_width_mm(columns) -> float | None:
    """One representative width for a shape's columns, for the shape-level underlay-band choice.

    The median of each column's median width. Returns None when no column has width (so the
    caller falls back to per-column widths). Deciding the underlay band from this, rather than
    each column's own width, keeps the band consistent across one shape: two near-identical stems
    (e.g. an H's legs at 2.01 and 1.92 mm) straddling a FABRICS width threshold would otherwise get
    different underlay. The split-satin decision stays per column (a wide column snags regardless
    of its neighbours)."""
    import statistics

    meds = [sorted(w)[len(w) // 2] for w in (c.widths() for c in columns) if w]
    return statistics.median(meds) if meds else None


def _lettering_satin_params(widths_mm: list[float], pull_comp_mm: float | None = None,
                            fabric: str = "standard", band_width_mm: float | None = None,
                            suppress_short_stitch: bool = False) -> dict:
    """Satin params for one planned column, from its median width and the fabric preset.

    Underlay by width (FABRICS): a centre walk below center_below_mm, an edge
    walk (contour) above it, edge walk plus zigzag from zigzag_from_mm. The
    centre-walk-vs-contour band is chosen from band_width_mm when given (a
    shape-level representative width, so every column of one shape agrees on
    that band; see shape_band_width_mm), else from this column's own median
    width. The zigzag reinforcement stays per column: it is an add-on for a
    genuinely wide column, so a shape of mixed widths doesn't zigzag its
    medium columns just because its representative width is wide. Columns
    wider than SPLIT_SATIN_MM get the engine's split satin
    (max_stitch_length_mm), because one long stitch snags, and that too stays
    a per-column decision. pull_comp_mm overrides the preset's. Every name
    here is checked against the mined schema by _apply_params_to_element
    (readers: lib/elements/satin_column.py zigzag_spacing_mm,
    pull_compensation_mm, center_walk_underlay, contour_underlay,
    zigzag_underlay, max_stitch_length_mm).
    """
    from cli_anything_inkstitch.trace.glyph_columns import SPLIT_SATIN_MM

    f = FABRICS[fabric]
    w = sorted(widths_mm)[len(widths_mm) // 2] if widths_mm else 0.0
    bw = w if band_width_mm is None else band_width_mm   # the centre/contour band width
    pc = f["pull_comp_mm"] if pull_comp_mm is None else pull_comp_mm
    p = {"pull_compensation_mm": f"{pc:g}"}
    if f["spacing_mm"] is not None:
        p["zigzag_spacing_mm"] = f"{f['spacing_mm']:g}"
    if f.get("short_inset") is not None:
        # A sharp inner-rail kink (a tail joining a ring) piles the short-stitch inset into two bare
        # wedges; the column reads better with it off, at the same density (see short_stitch_kink).
        p["short_stitch_inset"] = "0" if suppress_short_stitch else f["short_inset"]
        p["short_stitch_distance_mm"] = f"{f['short_dist_mm']:g}"
    if bw < f["center_below_mm"]:
        p["center_walk_underlay"] = "true"
    else:
        p["contour_underlay"] = "true"
        if w >= f["zigzag_from_mm"]:
            p["zigzag_underlay"] = "true"
    if max(widths_mm or [0.0]) > SPLIT_SATIN_MM:
        p["max_stitch_length_mm"] = f"{SPLIT_SATIN_MM:g}"
        if p.get("zigzag_underlay") == "true" and fabric != "standard":
            # the zigzag underlay crosses the column too and has its own limit (empty by default:
            # a 10 mm column's underlay sewed 10 mm stitches). "standard" keeps its old output.
            p["zigzag_underlay_max_stitch_length_mm"] = f"{SPLIT_SATIN_MM:g}"
    return p


