# Scale-preservation contract per tool: allowed relative span deviation for
# svg/units.py check_scale_drift (that module documents the measured engine
# px-space write bug this refuses).
#
#   strict — routing tools rewrite every element but must keep the art's
#            scale exactly (5% span tolerance covers stitch-path jitter).
#   loose  — centerline-ish converters keep spans within a stroke/band
#            width, so only a multiplicative rescale (>1.5×) is refused.
#   None   — the span comparison is meaningless: cleanup removes elements,
#            and stroke_to_satin legitimately collapses a zigzag run's span
#            to the satin band around its spine (measured 20 → 6.6 units on
#            a plain wavy stroke).
_SCALE_GUARD = {
    "auto_run": 0.05,
    "auto_satin": 0.05,
    "stroke_to_satin": None,
    "satin_to_stroke": 0.5,
    "flip": 0.5,
    "break_apart": 0.5,
    "cleanup": None,
}


def _strip_stale_underpaths(tree, ids):
    """Remove previous auto_run travel output before re-routing.

    The engine's router treats every Stroke it is given as art to cover
    (lib/stitches/auto_run.py autorun/_process_elements — no path_type
    filtering on input) and its create_element writes
    inkstitch:path_type='autorun-underpath' on the travel runs it generates.
    Feeding those back in re-routes travel as art: measured on the rose-bag
    design, 129 inputs became 320 elements with bean-stitched travel legs
    crossing empty fabric.  Travel is regenerated by every routing pass, so
    stale underpaths are dropped here (from both the document and the
    selection) rather than routed.
    """
    from cli_anything_inkstitch.svg.attrs import qname
    key = qname("path_type")
    removed = []
    for elem in list(tree.getroot().iter()):
        if elem.get(key) == "autorun-underpath":
            removed.append(elem.get("id") or "?")
            elem.getparent().remove(elem)
    kept_ids = [i for i in ids if i not in set(removed)]
    return kept_ids, removed


def _run_tool(ctx, project_path, extension_name, ids, args, *, pre_process=None):
    emit(ctx, run_tool_core(ctx, project_path, extension_name, ids, args,
                            pre_process=pre_process))


# engine extensions whose output contains satin columns worth simplifying
_SATIN_PRODUCERS = {"auto_satin", "stroke_to_satin", "fill_to_satin"}


def _normalize_new_satins(extension_name: str, new_tree) -> int:
    """Give engine-emitted satins an id and attribute paints.

    fill_to_satin emits satin columns with NO id and their colors buried
    in a style attribute (measured on v3.3.0; the celtic v9 build fixed
    this by hand and the lesson was nearly lost: the artifact editor's
    design payload SKIPS id-less elements, so the satin exists, stitches,
    and exports — but is invisible and uneditable in the editor). Assign
    fsat_N ids and lift stroke/fill out of style (style wins the SVG
    cascade, so the stale declarations must go).
    """
    if extension_name not in _SATIN_PRODUCERS:
        return 0
    import re as _re
    ink_sat = "{http://inkstitch.org/namespace}satin_column"
    root = new_tree.getroot()
    taken = {e.get("id") for e in root.iter() if e.get("id")}
    n = 0
    fixed = 0
    for el in root.iter():
        if not isinstance(el.tag, str):
            continue
        if (el.get(ink_sat) or "").lower() != "true":
            continue
        changed = False
        if not el.get("id"):
            while True:
                n += 1
                if f"fsat_{n}" not in taken:
                    break
            el.set("id", f"fsat_{n}")
            taken.add(f"fsat_{n}")
            changed = True
        style = el.get("style") or ""
        for prop in ("stroke", "fill"):
            m = _re.search(rf"(?:^|;)\s*{prop}\s*:\s*([^;]+)", style)
            if m and not el.get(prop):
                el.set(prop, m.group(1).strip())
                changed = True
        if changed and style:
            kept = [s for s in style.split(";") if s.strip()
                    and not s.strip().startswith(("stroke:", "fill:"))]
            if kept:
                el.set("style", ";".join(kept))
            else:
                el.attrib.pop("style", None)
        fixed += 1 if changed else 0
    return fixed


def _color_satin_underpaths(extension_name: str, new_tree) -> int:
    """Give auto_satin's travel strokes the stroke colour of the satins they run under.

    auto_satin builds each travel stroke's style from its source satin's `style` attribute only
    (lib/stitches/auto_satin.py RunningStitch.to_element). Once _normalize_new_satins has lifted a
    satin's colour out of `style` into a `stroke` attribute (any earlier engine tool run on the same
    document: text-to-satin routes one letter at a time), the next run's travel strokes come out with
    no stroke colour at all, and the engine never sews a path without one
    (lib/elements/utils/nodes.py node_to_elements: Stroke only when stroke_color is set). Their travel
    then sews as a jump instead of a running stitch under the satins (measured: a 9.4 mm untrimmed
    jump across a routed 'a'). The colour is taken from a satin in the same parent group (one
    auto_satin run routes one group of one colour). Returns how many strokes were coloured."""
    if extension_name != "auto_satin":
        return 0
    import re as _re
    ptype = "{http://inkstitch.org/namespace}path_type"
    ink_sat = "{http://inkstitch.org/namespace}satin_column"

    def colour(el):
        m = _re.search(r"(?:^|;)\s*stroke\s*:\s*([^;]+)", el.get("style") or "")
        c = (m.group(1).strip() if m else None) or el.get("stroke")
        return None if c in (None, "", "none") else c

    n = 0
    for el in new_tree.getroot().iter():
        if not isinstance(el.tag, str) or el.get(ptype) != "satin-underpath" or colour(el):
            continue
        parent = el.getparent()
        sib = next((colour(s) for s in (parent if parent is not None else [])
                    if isinstance(s.tag, str) and (s.get(ink_sat) or "").lower() == "true" and colour(s)), None)
        if sib:
            el.set("stroke", sib)
            n += 1
    return n


def _engine_rail_indices(paths) -> tuple[int, int]:
    """Which two of a satin's flattened subpaths the engine takes as its rails, in index order (rail
    0 sets the sewing direction). Mirrors lib/elements/satin_column.py rail_indices: with no rungs,
    both; with exactly one rung (three paths), the two that cross exactly one other; with more, those
    crossing more than two others; when that is ambiguous, the two longest. A rung can be longer than
    the rails (a short crossbar), and auto_satin's output can list a rung first, so neither "the
    first two" nor "the two longest" is safe on its own."""
    from shapely.geometry import LineString

    if len(paths) <= 2:
        return 0, 1
    ls = [LineString(p) for p in paths]
    hits = [sum(ls[i].intersects(ls[j]) for j in range(len(ls)) if j != i) for i in range(len(ls))]
    if len(ls) == 3:
        rails = [i for i in range(3) if hits[i] == 1 and ls[i].length > 0.1]
    else:
        rails = [i for i in range(len(ls)) if hits[i] > 2 and ls[i].length > 0.1]
    if len(rails) != 2:
        rails = sorted(sorted(range(len(ls)), key=lambda i: -ls[i].length)[:2])
    return rails[0], rails[1]


def _routed_handoffs(group, uu_per_mm: float) -> list:
    """Handoffs in an auto_satin-routed group that would sew as a jump, each with how to fix it.

    auto_satin's route assumes the engine's end_at_nearest_point, which pulls a satin's end toward
    the next element; with one-pass satins (that setting off) a satin finishes at its drawn end, and
    the gap to the next sewn element can exceed collapse_len. A handoff counts when, from either end
    rail point of the element (its last stitch lands on a rail; a running stitch's last point), the
    next element is farther than ONE_PASS_TRIM_MM less its margin (as plan_one_pass): a satin's
    outline (start_at_nearest_point, on by default: within collapse_len of it the engine stitches
    through), its first rail point when that is off (lib/elements/satin_column.py first_stitch), a
    running stitch's first point.

    Returns [{"after": element, "hide": (start, end) | None}]: "hide" is a straight travel from the
    element's end-pair middle to the next element's entry, when that line lies wholly under elements
    still to be sewn (the travel auto_satin itself sews under satins); otherwise None: trim after.
    Elements the engine won't sew (no stroke colour) are skipped."""
    import math
    import re as _re

    from shapely.geometry import LineString, Point, Polygon
    from shapely.ops import unary_union

    from cli_anything_inkstitch.artifact.design_model import split_subpaths
    from cli_anything_inkstitch.artifact.gate import flatten_path
    from cli_anything_inkstitch.svg.attrs import qname
    from cli_anything_inkstitch.trace import glyph_columns as gc

    sat, start_near, trim = qname("satin_column"), qname("start_at_nearest_point"), qname("trim_after")

    def stroked(e):
        m = _re.search(r"(?:^|;)\s*stroke\s*:\s*([^;]+)", e.get("style") or "")
        c = (m.group(1).strip() if m else None) or e.get("stroke")
        return c not in (None, "", "none")

    items = []
    for e in group.iter(f"{{{SVG_NS}}}path"):
        d = e.get("d")
        if not d or not stroked(e):
            continue
        subs = split_subpaths(d)
        if (e.get(sat) or "").lower() == "true":
            if len(subs) < 2:
                continue
            flat = [f for f in (flatten_path(x) for x in subs) if len(f) > 1]
            if len(flat) < 2:
                continue
            i0, i1 = _engine_rail_indices(flat)
            L, R = flat[i0], flat[i1]
            if len(L) < 2 or len(R) < 2:
                continue
            # rail 1 runs the same way as rail 0 or is reversed to (satin_column.py
            # _get_rails_to_reverse): align it so its end is the one nearer rail 0's end
            if math.dist(R[0], L[-1]) < math.dist(R[-1], L[-1]):
                R = list(R)[::-1]
            r_end = R[-1]
            exact = (e.get(start_near) or "").lower() in ("false", "0")
            poly = Polygon(list(L) + list(R)[::-1]).buffer(0)
            items.append({"e": e, "exits": [L[-1], r_end],
                          "mid": ((L[-1][0] + r_end[0]) / 2, (L[-1][1] + r_end[1]) / 2),
                          "entry_pt": L[0], "poly": poly,
                          "entry_line": None if exact else LineString(gc.centre_line(L, R))})
        else:
            P = flatten_path(subs[0])
            if len(P) >= 2:
                items.append({"e": e, "exits": [P[-1]], "mid": P[-1], "entry_pt": P[0],
                              "entry_line": None, "poly": None})
    limit = (gc.ONE_PASS_TRIM_MM - gc.ONE_PASS_TRIM_MARGIN_MM) * uu_per_mm
    out = []
    for i, (a, b) in enumerate(zip(items, items[1:])):
        if (a["e"].get(trim) or "").lower() == "true":
            continue

        def entry(p):
            if b["entry_line"] is None:
                return b["entry_pt"]
            q = b["entry_line"].interpolate(b["entry_line"].project(Point(p)))
            return (q.x, q.y)

        # the engine jumps into a satin only when its outline is collapse_len away; nearer, it starts
        # from the outline and stitches through (lib/elements/satin_column.py start_point)
        if b["entry_line"] is not None and b["poly"] is not None:
            travel = max(b["poly"].distance(Point(p)) for p in a["exits"])
        else:
            travel = max(math.dist(p, entry(p)) for p in a["exits"])
        if travel <= limit:
            continue
        later = [x["poly"] for x in items[i + 1:] if x["poly"] is not None]
        start, end = a["mid"], entry(a["mid"])
        hide = None
        if later and math.dist(start, end) > 0:
            if unary_union(later).buffer(0.05 * uu_per_mm).contains(LineString([start, end])):
                hide = (start, end)
        out.append({"after": a["e"], "hide": hide})
    return out


def _simplify_new_satin_rails(extension_name: str, before_xml: str,
                              new_tree) -> dict | None:
    """RDP-simplify rails of satins the tool created or rewrote.

    Only elements whose d is new or changed vs the pre-tool document are
    touched — user-authored satins the tool ignored pass through untouched.
    Full contract in trace/satinize.py simplify_satin_d (bezier rails and
    rung subpaths are never modified).
    """
    if extension_name not in _SATIN_PRODUCERS:
        return None
    from cli_anything_inkstitch.trace.satinize import simplify_satin_d
    ink_satin = "{http://inkstitch.org/namespace}satin_column"
    before_root = etree.fromstring(before_xml.encode("utf-8"))
    before_d = {e.get("id"): e.get("d") for e in before_root.iter()
                if e.get("id") and e.get("d")}
    total_before = total_after = changed = 0
    for el in new_tree.getroot().iter():
        if not isinstance(el.tag, str):
            continue
        if (el.get(ink_satin) or "").lower() != "true" or not el.get("d"):
            continue
        eid = el.get("id")
        if eid and before_d.get(eid) == el.get("d"):
            continue                     # untouched by the tool — hands off
        new_d, nb, na = simplify_satin_d(el.get("d"))
        if na < nb:
            el.set("d", new_d)
            changed += 1
            total_before += nb
            total_after += na
    if not changed:
        return None
    return {"elements": changed, "rail_nodes_before": total_before,
            "rail_nodes_after": total_after}


def run_tool_core(ctx, project_path, extension_name, ids, args, *,
                  pre_process=None) -> dict:
    """Run a binary tool; if it returns SVG, swap it in. Returns the payload.

    Uses mutate=False — we save the SVG ourselves so open_project's exit-save
    doesn't clobber the binary's output with the original tree.
    """
    from cli_anything_inkstitch.svg.document import save_svg
    from cli_anything_inkstitch.svg.attrs import ensure_inkstitch_namespace
    from cli_anything_inkstitch.svg.units import (
        art_bbox,
        bake_transforms,
        check_scale_drift,
        unit_scale_warning,
    )
    with open_project(ctx, project_path, mutate=False) as (proj, _tree):
        binary = require(ctx.obj.get("binary_override"), proj.session)
        # snapshot for history BEFORE any pre-processing mutates the tree,
        # so undo restores the document exactly as it was
        before_xml = etree.tostring(_tree.getroot()).decode("utf-8")
        before_bbox = art_bbox(_tree)
        # routing rewrites the whole document; take a durable auto-checkpoint
        # so a bad pass is one restore away even after the history ring
        # forgets (checkpoints.py — a re-route once turned 129 elements into
        # 320 with no undo path left)
        if extension_name in ("auto_run", "auto_satin"):
            from cli_anything_inkstitch.checkpoints import record_checkpoint
            record_checkpoint(proj, _tree,
                              f"auto: before {extension_name}", auto=True)
            proj.save()
        unit_warning = unit_scale_warning(_tree.getroot())
        extra_payload = {}
        if pre_process is not None:
            ids, extra_payload = pre_process(_tree, ids)
            if extra_payload:
                # pre-processing changed the document — the binary reads from
                # disk, so flush before invoking it
                save_svg(_tree, proj.svg_path)
        stdout = run_extension(binary, extension_name, proj.svg_path,
                                args=args, ids=ids, capture_stdout=True)
        if not stdout:
            if extra_payload:
                # pre-processing already changed the doc; record + keep it
                push(proj.history, make_entry(
                    command=f"tools {extension_name} (pre-process only)",
                    patch=document_replace(
                        before_xml,
                        etree.tostring(_tree.getroot()).decode("utf-8"))))
                proj.svg_sha256 = save_svg(_tree, proj.svg_path)
                proj.save()
            # Empty stdout = nothing applicable; not an error.
            return {"tool": extension_name, "ids": ids, "changed": bool(extra_payload),
                    "note": "no changes — selection may not match tool requirements",
                    **extra_payload}
        new_tree = etree.ElementTree(etree.fromstring(stdout))
        ensure_inkstitch_namespace(new_tree)
        # engine tools may leave their px-space correction transform as an
        # attribute (svg/units.py has the measured details) — bake it so raw
        # path data equals effective geometry for every downstream reader
        baked = bake_transforms(new_tree)
        # refuse silently-rescaled output before it reaches the document —
        # see _SCALE_GUARD for the measured engine behavior this catches
        tol = _SCALE_GUARD.get(extension_name, 0.5)
        try:
            if tol is not None:
                check_scale_drift(extension_name, before_bbox,
                                  art_bbox(new_tree), tol)
        except UserError:
            # roll the on-disk SVG back to the pre-tool state (pre_process
            # may have flushed a mutated tree above)
            if extra_payload:
                restored = etree.ElementTree(
                    etree.fromstring(before_xml.encode("utf-8")))
                save_svg(restored, proj.svg_path)
            raise
        # fill_to_satin fails SILENT when rungs mis-section a fill: it
        # consumes the fill and its rungs and emits NOTHING (measured on an
        # arc-band whose rungs came from degenerate geometry). Refuse to
        # save a document that lost the selection without gaining a satin.
        if extension_name == "fill_to_satin":
            ink_sat = "{http://inkstitch.org/namespace}satin_column"

            def _satins(node):
                return sum(1 for e in node.iter()
                           if isinstance(e.tag, str)
                           and (e.get(ink_sat) or "").lower() == "true")

            before_sats = _satins(etree.fromstring(before_xml.encode("utf-8")))
            if _satins(new_tree.getroot()) <= before_sats:
                if extra_payload:
                    restored = etree.ElementTree(
                        etree.fromstring(before_xml.encode("utf-8")))
                    save_svg(restored, proj.svg_path)
                raise UserError(
                    "fill_to_satin consumed the selection without emitting "
                    "a satin — the rungs did not section the fill (each "
                    "rung must cross the fill boundary exactly twice and "
                    "the sections must chain). Nothing was changed; check "
                    "the rung placement and retry.")
        # engine satins arrive id-less with style-buried colors — normalize
        # so the editor can see them (details on _normalize_new_satins)
        normalized = _normalize_new_satins(extension_name, new_tree)
        if normalized:
            extra_payload["normalized_satins"] = normalized
        colored = _color_satin_underpaths(extension_name, new_tree)
        if colored:
            extra_payload["colored_underpaths"] = colored
        # node economy: engine satin output samples its rails from the input
        # density — simplify NEW/CHANGED satin rails before they enter the
        # document (helper contract + reader citation: trace/satinize.py
        # simplify_satin_d)
        simplified = _simplify_new_satin_rails(extension_name, before_xml,
                                               new_tree)
        if simplified:
            extra_payload["simplified_rails"] = simplified
        # binary tools rewrite the whole document — record it so undo/redo
        # and the artifact History panel see it like any other edit
        push(proj.history, make_entry(
            command=f"tools {extension_name}" + (f" --ids {','.join(ids)}" if ids else ""),
            patch=document_replace(
                before_xml,
                etree.tostring(new_tree.getroot()).decode("utf-8"))))
        proj.svg_sha256 = save_svg(new_tree, proj.svg_path)
        proj.save()
        payload = {"tool": extension_name, "ids": ids, "changed": True,
                   "bytes": len(stdout), **extra_payload}
        if baked:
            payload["baked_transforms"] = baked
        if unit_warning:
            payload["unit_warning"] = unit_warning
        return payload


